import React from "react"
import ReactDOM from "react-dom/client"
import "./index.css"
import App from "./App"
import type { Snapshot } from "./types"

// Production: fomo1.py swaps the JSON into <script id="fomo1-data"> before saving output/dashboard.html.
// `npm run dev`: nothing is injected, so fall back to public/sample-data.json.
async function loadData(): Promise<Snapshot> {
  const txt = (document.getElementById("fomo1-data")?.textContent ?? "").trim()
  if (txt.startsWith("{")) return JSON.parse(txt) as Snapshot
  const res = await fetch("/sample-data.json")
  if (!res.ok) throw new Error("not found")
  return (await res.json()) as Snapshot
}

function Root() {
  const [snap, setSnap] = React.useState<Snapshot | null>(null)
  const [failed, setFailed] = React.useState(false)
  React.useEffect(() => {
    loadData().then(setSnap).catch(() => setFailed(true))
  }, [])
  if (failed)
    return (
      <div className="mx-auto max-w-xl p-10 text-sm text-muted-foreground">
        <h1 className="mb-2 text-lg font-semibold text-foreground">No data in this file</h1>
        Open <code>output/dashboard.html</code> generated by <code>python fomo1.py run</code> (or <code>render</code>). This is the empty template.
      </div>
    )
  if (!snap) return <div className="p-10 text-sm text-muted-foreground">Loading…</div>
  return <App snap={snap} />
}

ReactDOM.createRoot(document.getElementById("root")!).render(
  <React.StrictMode>
    <Root />
  </React.StrictMode>
)
