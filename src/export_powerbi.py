"""Export the readiness snapshot as tables for Power BI, and create the Power BI project on first run.

Usage (from the project folder): py src/export_powerbi.py [YYYY-MM-DD] [--rebuild-project]

Writes to data/powerbi/ (git-ignored, overwritten on every run so a Power BI refresh picks up the latest data):
    systems.csv, assets.csv, references.csv, lifecycle.csv, meta.csv
and, if it does not exist yet (or with --rebuild-project), the Power BI project
    data/powerbi/Forma System Readiness.pbip   (generated by powerbi_project.py)
with this machine's data folder filled in.
Open the .pbip in Power BI Desktop and press Refresh after each .\\refresh.ps1.
"""

import csv
import json
import sys

import config
import powerbi_project
import render

OUT = config.ROOT / "data" / "powerbi"

STATE_LABELS = {"blocking": "Blocking", "unknown": "Unknown", "done": "Done", "info": "Reference"}
READINESS_LABELS = {"ready": "Ready", "not_ready": "Not ready", "unknown": "Unknown", "unassigned": "No system"}
READINESS_ORDER = {"not_ready": 1, "unknown": 2, "ready": 3, "unassigned": 4}


def write_csv(name, header, rows):
    path = OUT / f"{name}.csv"
    with path.open("w", encoding="utf-8", newline="") as f:
        w = csv.writer(f)
        w.writerow(header)
        w.writerows(rows)
    return len(rows)


def tables(data):
    """Turn the dashboard data (render.build_data) into flat rows."""
    phases = {p["id"]: (p["label"], i + 1) for i, p in enumerate(data["phases"])}
    systems = [[s["id"], s["name"], s["status"], READINESS_LABELS.get(s["status"], s["status"]),
                READINESS_ORDER.get(s["status"], 9), str(s["isUnassigned"]).lower(), s["assetCount"],
                s["assetsWithReferences"], s["assetsNotReady"], s["assetsUnknown"], s["blockingCount"]]
               for s in data["systems"]]
    assets, refs = [], []
    for a in data["assets"]:
        key = f"{a['lifecycleSetId']}|{a['lifecycleStep']}" if a.get("lifecycleSetId") and a.get("lifecycleStep") else ""
        assets.append([a["id"], a["name"], (a["systemIds"] or ["(no system)"])[0], a.get("category") or "",
                       a.get("barcode") or "", a.get("assetStatus") or "", a["status"],
                       READINESS_LABELS.get(a["status"], a["status"]), READINESS_ORDER.get(a["status"], 9),
                       a["blockingCount"], a["unknownCount"], a["refCount"], key, a.get("url") or ""])
        for r in a["references"]:
            phase, order = phases.get(r["phase"], (r["phase"], 9))
            link = "linked directly" if r["depth"] <= 1 else "via " + " > ".join(r["path"][:-1])
            refs.append([a["id"], r["key"], r["typeLabel"], r["label"], r["state"], STATE_LABELS.get(r["state"], r["state"]),
                         phase, order, r.get("status") or "", r.get("itemType") or "", r.get("dueDate") or "",
                         r["depth"], link, r.get("url") or ""])
    lifecycle = [[f"{sid}|{i + 1}", s["name"], f"{i + 1:02d} {label}", i + 1]
                 for sid, s in data["lifecycleSets"].items() for i, label in enumerate(s["steps"])]
    m = data["meta"]
    meta = [[m.get("projectName") or "", m.get("snapshotDay") or "", m.get("generatedAtLocal") or "", m.get("maxDepth"),
             m.get("issueDoneStatuses") or "", m.get("formDoneStatuses") or "", m.get("systemAttribute") or ""]]
    return {
        "systems": (["SystemId", "System", "Status", "Readiness", "ReadinessOrder", "IsUnassigned", "Assets",
                     "AssetsWithLinks", "AssetsNotReady", "AssetsUnknown", "BlockingItems"], systems),
        "assets": (["AssetId", "Asset", "SystemId", "Category", "Barcode", "AssetStatus", "Status", "Readiness",
                    "ReadinessOrder", "BlockingCount", "UnknownCount", "ReferenceCount", "LifecycleKey", "FormaUrl"], assets),
        "references": (["AssetId", "ItemKey", "ItemType", "Item", "State", "StateLabel", "Phase", "PhaseOrder",
                        "ItemStatus", "Detail", "DueDate", "Depth", "LinkPath", "FormaUrl"], refs),
        "lifecycle": (["LifecycleKey", "LifecycleSet", "Step", "StepNumber"], lifecycle),
        "meta": (["Project", "SnapshotDay", "GeneratedAt", "MaxDepth", "IssueDoneStatuses", "FormDoneStatuses",
                  "SystemGrouping"], meta),
    }


def build_project(rebuild=False):
    """Create the Power BI project next to the data, with this machine's data folder filled in."""
    pbip = OUT / f"{powerbi_project.NAME}.pbip"
    if pbip.exists() and not rebuild:
        return pbip, False
    return powerbi_project.write_project(OUT, str(OUT) + "\\"), True


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    day = args[0] if args else config.snapshot_day()
    path = config.snapshot_dir(day) / "readiness.json"
    if not path.exists():
        raise SystemExit(f"{path} not found. Run .\\refresh.ps1 (or py src/readiness.py) first.")
    models_path = path.parent / "models.json"
    models = json.loads(models_path.read_text(encoding="utf-8")) if models_path.exists() else None
    data = render.build_data(json.loads(path.read_text(encoding="utf-8")), models=models)
    OUT.mkdir(parents=True, exist_ok=True)
    for name, (header, rows) in tables(data).items():
        print(f"  {name + '.csv':<16} {write_csv(name, header, rows):>6} rows")
    pbip, created = build_project("--rebuild-project" in sys.argv)
    print(f"Power BI data in {OUT}")
    print(("Created " if created else "Project already there (keeps your edits): ") + str(pbip))
    print("Open it in Power BI Desktop and press Refresh to load the latest data.")


if __name__ == "__main__":
    main()
